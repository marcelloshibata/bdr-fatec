DROP DATABASE IF EXISTS rede_hortifruti;
CREATE DATABASE rede_hortifruti CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE rede_hortifruti;

SET NAMES utf8mb4;

CREATE TABLE loja (
  id_loja INT PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  cidade VARCHAR(60) NOT NULL,
  bairro VARCHAR(60) NOT NULL
);

CREATE TABLE categoria (
  id_categoria INT PRIMARY KEY,
  nome VARCHAR(60) NOT NULL
);

CREATE TABLE produto (
  id_produto INT PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  preco DECIMAL(10,2) NOT NULL,
  estoque INT NOT NULL,
  id_categoria INT NOT NULL,
  CONSTRAINT fk_produto_categoria FOREIGN KEY (id_categoria) REFERENCES categoria(id_categoria)
);

CREATE TABLE cliente (
  id_cliente INT PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  cidade VARCHAR(60) NOT NULL,
  data_cadastro DATE NOT NULL
);

CREATE TABLE pedido (
  id_pedido INT PRIMARY KEY,
  data_pedido DATE NOT NULL,
  id_cliente INT NOT NULL,
  id_loja INT NOT NULL,
  CONSTRAINT fk_pedido_cliente FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente),
  CONSTRAINT fk_pedido_loja FOREIGN KEY (id_loja) REFERENCES loja(id_loja)
);

CREATE TABLE item_pedido (
  id_item INT PRIMARY KEY,
  id_pedido INT NOT NULL,
  id_produto INT NOT NULL,
  quantidade INT NOT NULL,
  preco_unitario DECIMAL(10,2) NOT NULL,
  CONSTRAINT fk_item_pedido FOREIGN KEY (id_pedido) REFERENCES pedido(id_pedido),
  CONSTRAINT fk_item_produto FOREIGN KEY (id_produto) REFERENCES produto(id_produto)
);

CREATE INDEX idx_produto_categoria ON produto(id_categoria);
CREATE INDEX idx_cliente_cidade ON cliente(cidade);
CREATE INDEX idx_pedido_cliente ON pedido(id_cliente);
CREATE INDEX idx_pedido_loja ON pedido(id_loja);
CREATE INDEX idx_pedido_data ON pedido(data_pedido);
CREATE INDEX idx_item_pedido ON item_pedido(id_pedido);
CREATE INDEX idx_item_produto ON item_pedido(id_produto);

